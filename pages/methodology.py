import streamlit as st

st.title("Methodology")

# ── Data Flows & Implementation Details ──

st.header("Data Flows & Implementation Details")

st.subheader("1. Data Collection (Web Scraping)")
st.write(
    "When running locally, the scraper connects to the Place2Lease public API on app startup to "
    "fetch all available commercial unit listings. It paginates through the "
    "search endpoint to discover every unit ID, then calls the detail endpoint "
    "for each unit to retrieve full specifications and conditions. "
    "On the live web version (Streamlit Cloud), the HDB API is not accessible from external servers, "
    "so pre-scraped data is loaded from a bundled JSON file instead."
)
st.markdown("""
- **Search API** — Discovers all unit IDs via `/tender-units/public/search-tender-units` with pagination
- **Detail API** — Fetches each unit's full data via `/tender-units/public/view/{id}`
- **BeautifulSoup** — Parses HTML in the "Important Unit Conditions" field into clean, readable text
- **Output** — Structured JSON (`place2lease_units.json`) and a plain-text corpus (`place2lease_corpus.txt`)
""")

st.subheader("2. Pre-Retrieval Process (Region Enrichment)")
st.write(
    "Before documents are loaded into the RAG pipeline, each unit's corpus entry is "
    "enriched with region information derived from a town-to-region mapping file "
    "(`resources/town_region.txt`). This allows the chatbot to answer region-based "
    "questions (e.g. \"how many units in the East?\") accurately."
)
st.markdown("""
- **Town-Region Mapping** — Loaded from `town_region.txt` at startup, mapping each HDB town to its region (e.g. Bedok → East, Woodlands → North)
- **Corpus Enrichment** — A `Region` field is appended to each unit's text entry in the corpus before chunking
- **Structured Summary** — A compact summary of all units (with town, region, type, and trades) is passed alongside retrieved chunks as additional context, enabling the LLM to answer counting and aggregation questions across the full dataset
""")

st.subheader("3. Document Loading")
st.write("Four data sources are ingested into the RAG pipeline:")
st.markdown("""
| Document | Type | How It's Loaded |
|----------|------|----------------|
| Place2Lease Listings | Scraped locally / Pre-loaded on cloud | Generated by the scraper at startup (local) or loaded from bundled JSON (cloud), enriched with region info |
| FAQ | Text file | Read directly from `resources/FAQ.txt` |
| e-Bidding Terms and Conditions | PDF | Text extracted with **pypdf** |
| Town-Region Mapping | Text file | Read from `resources/town_region.txt` |
""")

st.subheader("4. Splitting & Chunking")
st.write(
    "Each document is split into smaller overlapping chunks using LangChain's "
    "`RecursiveCharacterTextSplitter` to preserve semantic coherence across chunk boundaries."
)
st.markdown("""
- **Chunk size:** 500 characters
- **Chunk overlap:** 50 characters
- **Separators:** Paragraph breaks → line breaks → spaces
""")

st.subheader("5. Embedding & Vector Storage")
st.write(
    "Each chunk is converted into a vector embedding and stored in a ChromaDB "
    "vector store for efficient similarity search at query time."
)
st.markdown("""
- **Embedding model:** OpenAI `text-embedding-3-small`
- **Vector store:** ChromaDB (persisted locally)
- **Metadata:** Each chunk retains its source document name for citation
""")

st.subheader("6. Retrieval & Response Generation")
st.write(
    "When a user asks a question, the system retrieves the most relevant chunks "
    "from the vector store and combines them with a structured summary of all units "
    "(including region data) as context for the language model."
)
st.markdown("""
- **Retrieval:** Top-10 similarity search from ChromaDB
- **Structured context:** A compact all-units summary (town, region, type, trades) is prepended to the retrieved chunks, enabling accurate counting and aggregation answers
- **LLM:** OpenAI `gpt-4o-mini`
- **Prompt strategy:** System prompt instructs the model to answer strictly from retrieved context
""")

st.divider()

